"""Writes data/prepared/VALIDATION_REPORT.md and data/prepared/district_crosswalk.csv."""
from __future__ import annotations

import datetime as dt

import pandas as pd

from .common import PREPARED, RAW, REF, Report


def _md_table(df: pd.DataFrame, max_rows: int = 60) -> str:
    if df is None or not len(df):
        return "_none_\n"
    d = df.head(max_rows).astype(str)
    lines = ["| " + " | ".join(d.columns) + " |", "|" + "---|" * len(d.columns)]
    lines += ["| " + " | ".join(v.replace("|", "/") for v in row) + " |" for row in d.values]
    more = f"\n_…{len(df) - max_rows} more rows_\n" if len(df) > max_rows else ""
    return "\n".join(lines) + "\n" + more


def write(report: Report) -> None:
    cw = [report.tables[k] for k in report.tables if k.startswith("crosswalk_")]
    if cw:
        allcw = pd.concat(cw, ignore_index=True)
        allcw.to_csv(PREPARED / "district_crosswalk.csv", index=False)
        allcw.to_csv(REF / "district_crosswalk.csv", index=False)
        report.wrote("district_crosswalk.csv", allcw, grain="source name → canonical id")
    shutil_ref = REF / "crop_mapping.csv"
    if shutil_ref.exists():
        cm = pd.read_csv(shutil_ref)
        cm.to_csv(PREPARED / "crop_mapping.csv", index=False)
        report.wrote("crop_mapping.csv", cm, grain="source crop → canonical crop")

    out = ["# Validation report", "", f"Generated by `python -m pipeline.run_all` at {dt.datetime.now(dt.timezone.utc).isoformat(timespec='seconds')} (run started {report.started}).", ""]
    out += ["Every number below is computed from the files in `data/raw/` during the run. Nothing is typed in by hand.", ""]
    out += ["## Prepared files", "", "| File | Rows | Grain / status |", "|---|---:|---|"]
    for name, meta in sorted(report.files.items()):
        out.append(f"| `{name}` | {meta['rows']:,} | {meta.get('grain') or meta.get('status', '')} |")
    out += ["", "## Raw sources", ""]
    man = RAW / "manifest.csv"
    if man.exists():
        m = pd.read_csv(man).fillna("")
        out.append(_md_table(m[["id", "path", "status", "retrieved_utc", "licence"]], 100))
    out += ["", "## Source status in this run", ""]
    for sid, meta in sorted(report.sources.items()):
        extra = ", ".join(f"{k}={v}" for k, v in meta.items() if k != "status")
        out.append(f"- **{sid}**: {meta['status']}{' — ' + extra if extra else ''}")
    for section, lines in report.sections.items():
        out += ["", f"## {section}", ""] + [f"- {ln}" for ln in lines]
    if cw:
        allcw = pd.concat(cw, ignore_index=True)
        out += ["", "## District crosswalk summary", "", _md_table(allcw.groupby(["source", "method"]).size().rename("names").reset_index())]
        um = allcw[allcw["method"] == "unmatched"]
        out += ["", "### Unmatched district names", "", _md_table(um[["source", "source_state", "source_district"]], 200)]
    for k in ("crops_coverage_by_year", "groundwater_coverage_by_year", "rain_basis_by_year"):
        if k in report.tables:
            out += ["", f"## Coverage: {k.replace('_', ' ')}", "", _md_table(report.tables[k], 80)]
    if "crops_excluded_yield" in report.tables:
        out += ["", "## Excluded records: implausible yields", "", _md_table(report.tables["crops_excluded_yield"], 120)]
    (PREPARED / "VALIDATION_REPORT.md").write_text("\n".join(out) + "\n")
